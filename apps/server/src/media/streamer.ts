import { createReadStream, type ReadStream } from "node:fs";
import type { OutgoingHttpHeaders } from "node:http";
import { pipeline } from "node:stream";
import { stat } from "node:fs/promises";
import type { FastifyReply } from "fastify";

// Fastify's `reply.send(fsReadStream)` has a known incompatibility on this
// Node version: the response resolves as "completed" immediately while zero
// bytes are actually flushed (confirmed via a minimal repro — a plain
// in-memory Readable works fine through reply.send, but an fs.ReadStream
// silently produces an empty body). Writing directly to the raw response via
// reply.hijack() bypasses Fastify's stream handling entirely and works
// correctly, so every body-bearing response below goes through this path
// instead of reply.send(stream).
//
// Headers set on the reply beforehand (reply.header) live on Fastify's reply,
// not on the raw response, so they are merged in explicitly: a hijacked reply
// otherwise silently dropped the vault's `Cache-Control: private, no-store`
// and the backup download's Content-Disposition.
function rawHeaders(
  reply: FastifyReply,
  headers: Record<string, string | number>
): OutgoingHttpHeaders {
  return { ...reply.getHeaders(), ...headers } as OutgoingHttpHeaders;
}

function pipeToRaw(
  reply: FastifyReply,
  stream: ReadStream,
  statusCode: number,
  headers: Record<string, string | number>
): void {
  reply.hijack();
  reply.raw.writeHead(statusCode, rawHeaders(reply, headers));
  // pipeline() rather than .pipe(): .pipe() does not destroy the source when
  // the destination closes early, and closing early is the *normal* case for
  // video — every seek aborts the previous range request. Each one leaked an
  // open file descriptor until the process ran out of them. pipeline tears
  // both ends down on completion, error or client abort alike.
  pipeline(stream, reply.raw, () => {
    // Errors here are a client hanging up mid-body or a read failing after
    // headers went out; both ends are already destroyed, nothing to answer.
  });
}

/** A body-less response (HEAD), sent through the same hijacked path. */
function headToRaw(
  reply: FastifyReply,
  statusCode: number,
  headers: Record<string, string | number>
): void {
  // Hijacked like the body path. Writing to reply.raw without it left Fastify
  // believing the reply was still pending, so it tried to send its own
  // response afterwards and logged "Reply already sent" on every HEAD.
  reply.hijack();
  reply.raw.writeHead(statusCode, rawHeaders(reply, headers));
  reply.raw.end();
}

export async function streamFile(
  reply: FastifyReply,
  filePath: string,
  mimeType: string,
  rangeHeader: string | undefined,
  isHead: boolean
): Promise<void> {
  let size: number;
  try {
    size = (await stat(filePath)).size;
  } catch {
    // Callers set a long immutable Cache-Control before calling this — it's
    // meant for the image, but a failure sent afterwards inherits it, and the
    // browser then pins the failure for a year and stops asking. A poster
    // generated by the next scan would never appear, and a transient error
    // would look permanent.
    reply.header("Cache-Control", "no-store");
    reply.code(404).send({ error: "File not found on disk" });
    return;
  }

  if (!rangeHeader) {
    const headers = {
      "Accept-Ranges": "bytes",
      "Content-Type": mimeType,
      "Content-Length": size,
    };
    if (isHead) {
      headToRaw(reply, 200, headers);
      return;
    }
    pipeToRaw(reply, createReadStream(filePath), 200, headers);
    return;
  }

  const match = /^bytes=(\d*)-(\d*)$/.exec(rangeHeader);
  if (!match) {
    reply.code(416).header("Content-Range", `bytes */${size}`).send();
    return;
  }

  const [, startStr, endStr] = match;
  let start = startStr ? Number(startStr) : 0;
  let end = endStr ? Number(endStr) : size - 1;

  if (!startStr && endStr) {
    // "bytes=-N" means the last N bytes
    start = Math.max(0, size - Number(endStr));
    end = size - 1;
  }

  if (Number.isNaN(start) || Number.isNaN(end) || start > end || end >= size) {
    reply.code(416).header("Content-Range", `bytes */${size}`).send();
    return;
  }

  const headers = {
    "Accept-Ranges": "bytes",
    "Content-Type": mimeType,
    "Content-Range": `bytes ${start}-${end}/${size}`,
    "Content-Length": end - start + 1,
  };

  if (isHead) {
    headToRaw(reply, 206, headers);
    return;
  }

  pipeToRaw(reply, createReadStream(filePath, { start, end }), 206, headers);
}
